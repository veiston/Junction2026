#!/usr/bin/env python3
"""Generate backend and frontend contract code from contracts/.

Run from backend/:  uv run python ../scripts/gen_contracts.py

Outputs (all start with a DO NOT EDIT header, wiped and rewritten on every run):
  backend/contracts/dto/<stem>.py          Pydantic v2 models from contracts/dto/<stem>.schema.json
  backend/contracts/interfaces/**          copy of contracts/interfaces/**/*.py
  frontend/src/contracts/index.ts          TypeScript types from contracts/dto
  frontend/src/contracts/widget-registry.ts  copy of contracts/interfaces/frontend/*.ts
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "contracts"
PY_OUT = ROOT / "backend" / "contracts"
TS_OUT = ROOT / "frontend" / "src" / "contracts"
HEADER = "DO NOT EDIT. Generated by scripts/gen_contracts.py from contracts/ (version {v})."


def version() -> str:
    return (SRC / "VERSION").read_text().strip()


def load_schemas() -> dict[str, dict]:
    return {p.name.removesuffix(".schema.json"): json.loads(p.read_text())
            for p in sorted((SRC / "dto").glob("*.schema.json"))}


# ---------------------------------------------------------------- Python ---

def _rewrite_refs(node, stems):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k == "$ref" and isinstance(v, str):
                for s in stems:
                    v = v.replace(f"{s}.schema.json", f"{s}.json")
            else:
                v = _rewrite_refs(v, stems)
            out[k] = v
        return out
    if isinstance(node, list):
        return [_rewrite_refs(x, stems) for x in node]
    return node


def gen_python(schemas: dict[str, dict]) -> None:
    dto_out = PY_OUT / "dto"
    if PY_OUT.exists():
        shutil.rmtree(PY_OUT)
    dto_out.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for stem, schema in schemas.items():
            schema = _rewrite_refs(schema, list(schemas))
            schema["$id"] = f"{stem}.json"
            # The Widget oneOf only narrows `data` per type; Pydantic keeps `data` as a dict.
            # The per-type payload models are all generated and validated by the widget owners.
            w = schema.get("$defs", {}).get("Widget")
            if w:
                w.pop("oneOf", None)
            (tmp / f"{stem}.json").write_text(json.dumps(schema))
        subprocess.run(
            [sys.executable, "-m", "datamodel_code_generator",
             "--input", str(tmp), "--input-file-type", "jsonschema", "--output", str(dto_out),
             "--output-model-type", "pydantic_v2.BaseModel", "--use-annotated",
             "--disable-timestamp", "--formatters", "black", "--target-python-version", "3.10",
             "--use-standard-collections", "--use-union-operator", "--collapse-root-models"],
            check=True)
    comment = f"# {HEADER.format(v=version())}\n"
    for f in dto_out.glob("*.py"):
        text = f.read_text()
        # replace the codegen banner with ours
        lines = [ln for ln in text.splitlines(keepends=True) if not ln.startswith("# generated by")]
        f.write_text(comment + "".join(lines).lstrip("\n"))
    (PY_OUT / "__init__.py").write_text(comment)
    iface_out = PY_OUT / "interfaces"
    for src in (SRC / "interfaces").rglob("*.py"):
        dst = iface_out / src.relative_to(SRC / "interfaces")
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(comment + src.read_text())
    for d in [iface_out, *[p for p in iface_out.rglob("*") if p.is_dir()]]:
        init = d / "__init__.py"
        if not init.exists():
            init.write_text(comment)


# ------------------------------------------------------------ TypeScript ---

def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def ts_type(s: dict, indent: str = "") -> str:
    if "$ref" in s:
        return _ref_name(s["$ref"])
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "oneOf" in s or "anyOf" in s:
        return " | ".join(ts_type(x, indent) for x in s.get("oneOf", s.get("anyOf")))
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}, indent) for x in t)
    if t == "null":
        return "null"
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "array":
        inner = ts_type(s.get("items", {}), indent)
        return f"Array<{inner}>" if "|" in inner else f"{inner}[]"
    if t == "object" or "properties" in s:
        props = s.get("properties")
        if not props:
            return "Record<string, unknown>"
        req = set(s.get("required", []))
        lines = ["{"]
        for k, v in props.items():
            if v.get("description"):
                lines.append(f"{indent}  /** {v['description'].replace('*/', '* /')} */")
            lines.append(f"{indent}  {k}{'' if k in req else '?'}: {ts_type(v, indent + '  ')};")
        lines.append(indent + "}")
        return "\n".join(lines)
    return "unknown"


def gen_widget(defn: dict) -> str:
    """Discriminated union: one member per oneOf branch, narrowed on `type`."""
    base = {k: v for k, v in defn["properties"].items() if k not in ("type", "data")}
    members = []
    for branch in defn["oneOf"]:
        p = branch["properties"]
        members.append(
            "  | (WidgetBase & { type: %s; data: %s })" % (ts_type(p["type"]), ts_type(p["data"])))
    base_ts = ts_type({"type": "object", "properties": base, "required": [r for r in defn["required"] if r in base]})
    return f"interface WidgetBase {base_ts}\n\nexport type Widget =\n" + "\n".join(members) + ";\n"


def gen_ts(schemas: dict[str, dict]) -> None:
    if TS_OUT.exists():
        shutil.rmtree(TS_OUT)
    TS_OUT.mkdir(parents=True)
    out = [f"// {HEADER.format(v=version())}\n"]
    seen: dict[str, str] = {}
    for stem, schema in schemas.items():
        out.append(f"\n// ---- {stem}.schema.json ----\n")
        for name, d in schema.get("$defs", {}).items():
            if name in seen:
                raise SystemExit(f"duplicate type name {name} in {stem} and {seen[name]}")
            seen[name] = stem
            if d.get("description"):
                out.append(f"/** {d['description'].replace('*/', '* /')} */")
            if name == "Widget" and "oneOf" in d:
                out.append(gen_widget(d))
            elif d.get("type") == "object" and "properties" in d:
                out.append(f"export interface {name} {ts_type(d)}\n")
            else:
                out.append(f"export type {name} = {ts_type(d)};\n")
    (TS_OUT / "index.ts").write_text("\n".join(out))
    for src in (SRC / "interfaces" / "frontend").glob("*.ts"):
        (TS_OUT / src.name).write_text(f"// {HEADER.format(v=version())}\n" + src.read_text())


def main() -> None:
    schemas = load_schemas()
    gen_python(schemas)
    gen_ts(schemas)
    print(f"generated contracts v{version()}: {len(schemas)} schemas -> backend/contracts, frontend/src/contracts")


if __name__ == "__main__":
    main()
